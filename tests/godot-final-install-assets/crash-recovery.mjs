import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {applyDraftInstall,recoverDraftInstall,ASSET_LOCK_FILE,DRAFT_INSTANCES_FILE} from '../../desktop/godot/shared/draft_install.mjs';
const projectDir=fs.mkdtempSync(path.join(os.tmpdir(),'draft-crash-proof-'));
fs.mkdirSync(path.join(projectDir,'scenes'));fs.writeFileSync(path.join(projectDir,'scenes/world.tscn'),'[gd_scene format=3]\n[node name="World" type="Node2D"]\n');
const base={ok:true,applied:false,operationId:'initial',worldId:'world',instances:[],lock:{format:'craftmine.assets-lock/1',assets:[]}};
assert.equal(applyDraftInstall({projectDir,plan:base}).ok,true);
const names=['scenes/world.tscn',ASSET_LOCK_FILE,DRAFT_INSTANCES_FILE];const before=names.map(n=>fs.readFileSync(path.join(projectDir,n)));
const id='new-door',edit={format:'craftmine.godot-scene-edit/1',scene:names[0],parent:'.',nodeName:id,mode:'script-node',nodeType:'Node2D',extResource:{type:'Script',path:'door.gd',id:'2_door'},properties:{entity_id:JSON.stringify(id)},identity:{field:'entity_id',value:JSON.stringify(id),entityId:id},groups:[],inputActions:[]};
const args={projectDir,plan:{...base,operationId:'crashing'},payload:[],sceneEdits:[edit]};
const input=path.join(projectDir,'crash-input.json');fs.writeFileSync(input,JSON.stringify(args));
const child=spawnSync(process.execPath,[fileURLToPath(new URL('./crash-install.mjs',import.meta.url)),input],{windowsHide:true,timeout:15000,encoding:'utf8'});
if(child.error)throw child.error;assert.equal(child.status,73,child.stderr);
assert.notDeepEqual(fs.readFileSync(path.join(projectDir,names[0])),before[0]);
const restored=recoverDraftInstall({projectDir,operationId:'crashing'});assert.equal(restored.recovered,true);
for(const [index,name]of names.entries())assert.deepEqual(fs.readFileSync(path.join(projectDir,name)),before[index],name);
assert.equal(applyDraftInstall(args).ok,true,'retry after rollback succeeds');
console.log(JSON.stringify({passed:true,projectDir,childExit:child.status,restored:restored.restored}));
