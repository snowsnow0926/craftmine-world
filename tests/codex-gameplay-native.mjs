// Actual normal input events, real native check/application, no model or OS input.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {main} from '../scripts/codex-world-author.mjs';
import {readState} from '../scripts/lib/codex-world-session.mjs';
import {CodexWorldHost} from '../scripts/lib/codex-world-host.mjs';
import {startCodexLiveService} from '../scripts/lib/codex-live-service.mjs';
import {checkCurrentSource} from '../scripts/codex-live-world.mjs';
const [runtime,plugin,data]=process.argv.slice(2);
for(const value of [runtime,plugin,data])assert(value&&path.isAbsolute(value),'Pass explicit runtime, plugin and fresh profile');
await main(['init','--data',data,'--runtime',runtime,'--plugin',plugin,'--world','input-'+randomUUID()]);
const state=readState(data);let host=new CodexWorldHost({state,data}),live;
const report={passed:false,modelCalls:0,data,stages:[]};
const context={projectId:state.projectId,sessionId:state.sessionId,turnId:randomUUID()};
const tool=(name,args={})=>host.tools.find(t=>t.name===name).execute(args,{...context,toolCallId:randomUUID(),executionId:'native-input-fixture'});
const position=s=>s.state.body.player.position;
try {
  live=await startCodexLiveService({core:host.core,state,data});host=new CodexWorldHost({state,data,core:host.core,services:live});await host.start();
  await host.begin(context,'Install the authored normal-input fixture before acceptance baseline.');
  const index=await tool('godot_project_index');
  const scene=await tool('godot_file_read',{revision:index.revision,manifestHash:index.manifestHash,path:'scenes/creation.tscn'});
  const text=scene.text.replace('load_steps=5','load_steps=6').replace('[sub_resource','[ext_resource type="Script" path="res://scripts/input_fixture.gd" id="9_input"]\n\n[sub_resource')+'\n[node name="InputFixture" type="Node3D" parent="."]\nscript = ExtResource("9_input")\n';
  await tool('godot_project_patch',{revision:index.revision,manifestHash:index.manifestHash,operations:[
    {op:'put',path:'scenes/creation.tscn',text,expectedHash:index.files.find(f=>f.path==='scenes/creation.tscn').sha256},
    {op:'put',path:'scripts/input_fixture.gd',text:await fs.readFile(new URL('./fixtures/game-input-receiver.gd',import.meta.url),'utf8'),expectedHash:null},
  ]});
  await host.end(context,'completed');
  const check=await checkCurrentSource(host,state);await live.call('apply',{candidateId:check.candidateId});
  const formal=await host.core.call('godotRuntime.describe',{worldId:state.worldId});
  const contentBefore=await host.core.call('content.status',{worldId:state.worldId});
  const {worldId,buildId,instanceId}= (await live.call('status')).instance;
  const identity={worldId,buildId,instanceId};
  const segment=s=>live.gameplay(identity,s);
  const fOnly=await segment({keys:['KeyF'],frames:1,settleFrames:3});
  assert.equal(fOnly.status,'completed');assert.notEqual(fOnly.before.frame.sha256,fOnly.after.frame.sha256);
  assert.match(fOnly.after.diagnostics.console.map(l=>l.text).join('\n'),/FIXTURE_F true/);
  report.stages.push({name:'non-base-key',result:fOnly});
  const moved=await segment({keys:['KeyW','KeyF'],frames:30,settleFrames:60});
  report.stages.push({name:'held-and-released',result:moved});
  assert.equal(moved.status,'completed');assert.equal(moved.release.released,true);
  assert.match(moved.delivery.programSha256,/^[a-f0-9]{64}$/);assert(moved.after.frame.imagePath);
  assert(position(moved.after.snapshot)[2]<position(moved.before.snapshot)[2]-0.1);
  const logs=moved.after.diagnostics.console.map(l=>l.text).join('\n');
  assert.match(logs,/FIXTURE_F true/);assert.match(logs,/FIXTURE_F false/);assert.match(logs,/FIXTURE_W_POLL true/);assert.match(logs,/FIXTURE_W_POLL false/);
  const rest=await segment({frames:30,capture:false});assert.deepEqual(position(rest.after.snapshot),position(moved.after.snapshot));
  const mouse=await segment({buttons:['left'],motion:{x:18,y:-7},frames:3,settleFrames:2});report.stages.push({name:'button-motion',result:mouse});
  assert.match(mouse.after.diagnostics.console.map(l=>l.text).join('\n'),/FIXTURE_BUTTON 1 true/);
  assert.match(mouse.after.diagnostics.console.map(l=>l.text).join('\n'),/FIXTURE_MOTION/);
  for(const wrong of [{...identity,worldId:'foreign'},{...identity,buildId:'stale'},{...identity,instanceId:'stale'}])await assert.rejects(live.call('inputSegment',{identity:wrong,segment:{keys:['KeyW'],frames:5}}),/IDENTITY/);
  await assert.rejects(segment({keys:['KeyW'],frames:601}),/FRAME_RANGE/);
  const pending=segment({keys:['KeyW'],frames:300,settleFrames:60,capture:false});
  await new Promise(resolve=>setTimeout(resolve,500));
  await assert.rejects(live.call('cancelInputs',{identity:{...identity,instanceId:'stale'}}),/IDENTITY/);
  const cancel=await live.call('cancelInputs',{identity});assert.equal(cancel.released,true);
  const cancelled=await pending;assert.equal(cancelled.status,'cancelled');assert.equal(cancelled.release.released,true);report.stages.push({name:'cancelled',result:cancelled});
  const afterCancel=await segment({frames:30,capture:false});assert.deepEqual(position(afterCancel.before.snapshot),position(afterCancel.after.snapshot));
  const originalCall=host.core.call.bind(host.core);
  host.core.call=(method,args,...rest)=>method==='godotRuntime.saveProgress'?Promise.reject(Object.assign(Error('INJECTED_SAVE_FAILURE'),{errorCode:'INJECTED_SAVE_FAILURE'})):originalCall(method,args,...rest);
  assert.equal((await live.call('save')).status,'failed');await assert.rejects(live.call('close'),/INJECTED_SAVE_FAILURE/);
  host.core.call=originalCall;
  const contentAfter=await host.core.call('content.status',{worldId:state.worldId});
  assert.equal(contentAfter.headOid,contentBefore.headOid);
  const after=await host.core.call('godotRuntime.describe',{worldId:state.worldId});assert.equal(after.manifestHash,formal.manifestHash);assert.equal(after.sourceRevision,formal.sourceRevision);
  await live.call('pause');const saved=await live.call('save');assert.equal(saved.status,'persisted');
  report.unchangedSource={manifestHash:formal.manifestHash,sourceRevision:formal.sourceRevision,headOid:contentBefore.headOid};report.saved=saved;
  const diagnostics=await live.call('diagnostics');for(const view of diagnostics.views)assert.deepEqual(view.runtime.guard,{pointerLock:0,focus:0});
  await live.call('resume');const exiting=segment({keys:['KeyW'],frames:120,settleFrames:60,capture:false});
  await new Promise(resolve=>setTimeout(resolve,400));
  await host.stop({beforeCoreStop:()=>live.stop()});
  const releasedOnExit=await exiting;assert.equal(releasedOnExit.status,'cancelled');assert.equal(releasedOnExit.release.released,true);
  report.stages.push({name:'release-on-exit',result:releasedOnExit});
  const closeReceipt=JSON.parse(await fs.readFile(path.join(live.directory,'close.json'),'utf8'));report.saved=closeReceipt.saved;
  const guards=JSON.parse(await fs.readFile(path.join(live.directory,'guards.json'),'utf8'));assert.deepEqual(guards.violations,[]);assert.deepEqual(guards.pageErrors,[]);
  host=new CodexWorldHost({state,data});live=await startCodexLiveService({core:host.core,state,data});await live.call('open');await live.call('pause');
  assert.deepEqual((await live.call('snapshot')).state,closeReceipt.saved.snapshot);await host.stop({beforeCoreStop:()=>live.stop()});
  report.passed=true;
} finally {await fs.writeFile(path.join(data,'gameplay-native-report.json'),JSON.stringify(report,null,2));await live?.abandon();await host.core.stop();}
console.log(JSON.stringify({passed:report.passed,report:path.join(data,'gameplay-native-report.json')}));
